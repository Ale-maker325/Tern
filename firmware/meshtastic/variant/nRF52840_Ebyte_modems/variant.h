/*
 * UART1 (Serial1) зайнятий GPS. UART2 (Serial2): P0.06 (номер 6) = RX МК, P0.08 (номер 8) = TX МК.
 * Для модуля Serial: обмін текстовими повідомленнями із зовнішнім пристроєм
 * (інший МК, ПК через USB-UART, термінал). Логіка 3,3 В! Вузол перезавантажиться сам.
 *   meshtastic --set serial.enabled true --set serial.rxd 6 --set serial.txd 8
 *              --set serial.baud BAUD_9600 --set serial.mode TEXTMSG
 *   Режими: TEXTMSG — рядок → повідомлення в канал; SIMPLE — «прозорий» канал;
 *   NMEA — видача позиції у форматі NMEA. Вимкнути: --set serial.enabled false
 */

// Конфігурація апаратних інтерфейсів UART (послідовні порти)
