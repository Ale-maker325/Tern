/*
 * ----------------------------------------------------------------------------
 * КАЛІБРУВАННЯ ВИМІРЮВАННЯ БАТАРЕЇ З КОМАНДНОГО РЯДКА (без перепрошивки)
 * ----------------------------------------------------------------------------
 * Розкид резисторів (1–5 %) дає похибку в показах. Виправляється так:
 *   1. Виміряти мультиметром реальну напругу батареї: Uреал.
 *   2. Подивитися, що показує прошивка (поле "voltage" свого вузла):
 *        meshtastic --info
 *   3. Новий множник = поточний множник * Uреал / Uпрошивки.
 *      Поточний множник — ADC_MULTIPLIER вище (2S: 3.13636, 3S: 4.70370).
 *      Приклад: прошивка 8.05 В, мультиметр 8.20 В → 3.13636 * 8.20 / 8.05 = 3.1948
 *        meshtastic --set power.adc_multiplier_override 3.1948
 *   4. Перевірити приблизно через 1 хвилину (--info). Значення зберігається у flash вузла
 *      і має пріоритет над ADC_MULTIPLIER з цього файлу.
 *   Повернути множник із прошивки:  meshtastic --set power.adc_multiplier_override 0
 *   Подивитися:                     meshtastic --get power
 *
 * Живлення тільки від USB (без батареї) для цієї плати не передбачене: на АЦП ~5,3 В — нижче
 * нижньої точки OCV_ARRAY, і на екрані буде 0 % — це нормально.
 * ----------------------------------------------------------------------------
 */

// Підсумковий розрахунок реальної напруги для ядра прошивки Meshtastic
