/*
 * Швидка перевірка та налаштування з командного рядка.
 * Який чип знайдено і з якою потужністю він стартував — у лозі під час завантаження:
 *   meshtastic --noproto   (шукати «SX126x init result» — 0 означає успіх, і «Final Tx power»)
 * Поточні налаштування радіо:  meshtastic --get lora
 * Регіон (обов'язковий, без нього вузол не передає). 433 МГц (E22-400...): UA_433 або
 * EU_433; 868 МГц (E22-900...): UA_868 або EU_868:
 *   meshtastic --set lora.region UA_433
 * Пресет швидкості/дальності (однаковий в усіх вузлів мережі):
 *   meshtastic --set lora.modem_preset LONG_FAST     (або LONG_SLOW, MEDIUM_FAST, SHORT_FAST...)
 * Потужність — це потужність на виході ЧИПА SX126x (макс. 22), модуль E22-...M30S/M33S
 * додає своє підсилення (~+8…+11 дБ: 22 на чипі ≈ 30 дБм у M30S, ≈ 33 дБм у M33S);
 * 0 = максимум регіону. Потрібне перезавантаження (відбувається само):
 *   meshtastic --set lora.tx_power 22
 * Номер частотного слота (0 = автоматично за назвою каналу, інакше 1, 2, 3...):
 *   meshtastic --set lora.channel_num 0
 * Перевірка зв'язку з іншим вузлом:
 *   meshtastic --nodes                          (SNR/RSSI сусідів, коли їх чути)
 *   meshtastic --sendtext "тест"                (повідомлення в основний канал)
 *   meshtastic --traceroute "!a1b2c3d4"         (маршрут до вузла за його ID)
 *   meshtastic --request-telemetry --dest "!a1b2c3d4"  (запит телеметрії вузла)
 * Посилання на канали (щоб налаштувати другий вузол так само):
 *   meshtastic --qr-all      /     meshtastic --seturl "посилання"
 */

