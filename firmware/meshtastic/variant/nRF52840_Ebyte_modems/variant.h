/*
 * P0.20 (номер 20) → RX модуля GPS, P0.22 (номер 22) ← TX модуля GPS,
 * P0.24 (номер 24) — ключ живлення GPS (1 = живлення подано).
 * Піни вже прописані нижче, вводити їх у застосунку/CLI не потрібно. За замовчуванням GPS
 * «Not present» (EN тримається в нулі, модуль знеструмлений). Вузол перезавантажиться сам.
 *   Увімкнути GPS:               meshtastic --set position.gps_mode ENABLED
 *   Вимкнути (з можливістю
 *   увімкнути з меню вузла):     meshtastic --set position.gps_mode DISABLED
 *   GPS не встановлено:          meshtastic --set position.gps_mode NOT_PRESENT
 *   Подивитися налаштування:     meshtastic --get position
 *   Як часто GPS шукає позицію (сек; більше — менша витрата батареї):
 *     meshtastic --set position.gps_update_interval 120
 *   Як часто позиція надсилається в мережу (сек):
 *     meshtastic --set position.position_broadcast_secs 900
 *   Розумне надсилання (лише при переміщенні):
 *     meshtastic --set position.position_broadcast_smart_enabled true
 *   Без GPS — задати нерухому позицію вручну:
 *     meshtastic --setlat 50.4501 --setlon 30.5234 --setalt 150
 *     прибрати її:  meshtastic --remove-position
 *   Якщо модуль підключено на інші піни (зазвичай не потрібно):
 *     meshtastic --set position.rx_gpio 22 --set position.tx_gpio 20 --set position.gps_en_gpio 24
 *     (rx_gpio — прийом МК, тобто вивід, куди приходить TX модуля GPS)
 *   Перевірка: у лозі (meshtastic --noproto) рядки про GPS; після захоплення супутників
 *   координати видно в meshtastic --info. Перший холодний старт — до кількох хвилин
 *   під відкритим небом.
 */

// Конфігурація інтерфейсу підключення GPS-модуля (назви PIN_GPS_TX/RX дано з точки зору GPS-модуля)
#define PIN_GPS_TX (0 + 22) // Вивід P0.22: сюди приходить TX модуля GPS (для МК це прийом, RX)
#define PIN_GPS_RX (0 + 20) // Вивід P0.20: звідси дані йдуть на RX модуля GPS (для МК це передача, TX)
#define PIN_GPS_EN (0 + 24) // Вивід P0.24 (керування ключем живлення GPS-модуля)
#define GPS_UBLOX

// Назви, які використовує прошивка (з точки зору МК): піни підставляються, лише коли GPS увімкнено
#define GPS_RX_PIN PIN_GPS_TX // Прийом МК = P0.22
#define GPS_TX_PIN PIN_GPS_RX // Передача МК = P0.20
// За замовчуванням GPS вимкнено («Not present»). Користувач вмикає його в застосунку:
// Position -> GPS mode = Enabled (піни вже прописані вище). Значення 1 обов'язкове: макрос стоїть у #elif
#define GPS_DEFAULT_NOT_PRESENT 1

